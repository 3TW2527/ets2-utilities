using Ets2u.Core.Mods;
using Ets2u.Core.Sii;

namespace Ets2u.Core.Features;

/// <summary>Things that lower coach passenger satisfaction, each of which can be switched off on its own.</summary>
[Flags]
public enum CoachFactor
{
    None = 0,
    /// <summary>G-forces from accelerating, braking and cornering (both the normal and the harsh threshold).</summary>
    DrivingStyle = 1,
    Crashes = 2,
    Speeding = 4,
    Lateness = 8,
    /// <summary>Coach wear and damage, while driving and when new passengers board.</summary>
    CoachWear = 16,
    Offences = 32,
    /// <summary>Not a score penalty: the g-force limit that fails the job outright.</summary>
    JobFailure = 64,
    All = DrivingStyle | Crashes | Speeding | Lateness | CoachWear | Offences | JobFailure,
}

/// <summary>
/// Overrides def/bus_economy_data.sii so chosen factors stop lowering coach passenger satisfaction.
/// Each factor is its own penalty setting there (a per-passenger min-max range); a switched-off factor's
/// range becomes zero. Rewards for smooth, on-time driving are never changed.
/// </summary>
public static class CoachComfort
{
    public const string GamePath = "def/bus_economy_data.sii";
    const string Unit = "bus_economy_data";

    public static readonly ModSpec Mod = new(
        "ets2u_coach", "ETS2 Utilities: Coach comfort", "other",
        "Generated by ETS2 Utilities. Chooses what lowers coach passenger satisfaction. Change it from the app, not by hand.");

    public const string FailureLimitKey = "failure_acceleration_limit";
    public const string NewPassengerKey = "satisfaction_new_passenger";

    /// <summary>The penalty settings each factor controls.</summary>
    public static readonly IReadOnlyDictionary<CoachFactor, string[]> PenaltyKeys = new Dictionary<CoachFactor, string[]>
    {
        [CoachFactor.DrivingStyle] = ["satisfaction_acceleration_penalties[]"],
        [CoachFactor.Crashes] = ["satisfaction_crash_penalties[]"],
        [CoachFactor.Speeding] = ["satisfaction_speed_penalty"],
        [CoachFactor.Lateness] = ["satisfaction_late_penalty"],
        [CoachFactor.CoachWear] = ["satisfaction_core_wear_penalties[]", "satisfaction_new_passenger_core_wear_penalty"],
        [CoachFactor.Offences] = ["satisfaction_offence_penalty"],
    };

    /// <summary>
    /// A satisfaction penalty: the key ends in _penalty or _penalties. That leaves out the rewards for
    /// driving without penalties (satisfaction_no_penalty_reward...) and the cooldown timer.
    /// </summary>
    public static bool IsPenaltyKey(string key)
    {
        var bare = key.EndsWith("[]", StringComparison.Ordinal) ? key[..^2] : key;
        return bare.StartsWith("satisfaction_", StringComparison.Ordinal)
               && (bare.EndsWith("_penalty", StringComparison.Ordinal) || bare.EndsWith("_penalties", StringComparison.Ordinal));
    }

    /// <summary>Penalty settings in the game file that no factor covers (e.g. added by a game update).</summary>
    public static IReadOnlyList<string> UnmappedPenalties(SiiDocument doc, SiiUnit unit) =>
        unit.AllKeys.Where(IsPenaltyKey).Distinct()
            .Where(k => !PenaltyKeys.Values.Any(keys => keys.Contains(k)))
            .ToList();

    public static byte[] Build(byte[] stock, CoachFactor ignored, bool fullSatisfaction)
    {
        if (ignored == CoachFactor.None && !fullSatisfaction) return stock;
        var doc = SiiDocument.Parse(stock);
        var unit = doc.FindUnit(Unit) ?? throw new FormatException($"No {Unit} unit in {GamePath}.");

        foreach (var (factor, keys) in PenaltyKeys)
            if (ignored.HasFlag(factor))
                foreach (var key in keys)
                    doc.SetEach(unit, key, ZeroTuple);

        // -1 turns an axis off, as the stock file already does for two of the three.
        if (ignored.HasFlag(CoachFactor.JobFailure) && doc.GetValue(unit, FailureLimitKey) is not null)
            doc.SetValue(unit, FailureLimitKey, "(-1.0, -1.0, -1.0)");
        if (fullSatisfaction && doc.GetValue(unit, NewPassengerKey) is not null)
            doc.SetValue(unit, NewPassengerKey, "(1.0, 1.0)");
        return doc.ToBytes();
    }

    public static byte[] BuildMod(byte[] stock, CoachFactor ignored, bool fullSatisfaction) =>
        ScsModBuilder.Build(Mod, new Dictionary<string, byte[]> { [GamePath] = Build(stock, ignored, fullSatisfaction) });

    /// <summary>"(0.09, 0.18)" becomes "(0.0, 0.0)"; a plain number becomes "0.0".</summary>
    static string ZeroTuple(string value)
    {
        var v = value.Trim();
        if (!v.StartsWith('(')) return "0.0";
        var parts = v.Trim('(', ')').Split(',').Length;
        return "(" + string.Join(", ", Enumerable.Repeat("0.0", parts)) + ")";
    }
}
