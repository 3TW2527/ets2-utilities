using System.Globalization;
using Ets2u.Core.Mods;
using Ets2u.Core.Sii;

namespace Ets2u.Core.Features;

/// <summary>
/// Overrides def/economy_data.sii to multiply truck job pay and XP. Coach jobs have no
/// pay or XP rates in the game files (bus_economy_data.sii holds none), so this is trucks only.
/// </summary>
public static class Earnings
{
    public const string GamePath = "def/economy_data.sii";
    const string Unit = "economy_data";

    public static readonly string[] IncomeKeys = ["fixed_revenue", "revenue_coef_per_km", "cargo_market_revenue_coef_per_km"];
    public static readonly string[] XpKeys = ["exp_cargo_delivery", "exp_free_roam", "exp_road_discovery"];

    public const double MaxMultiplier = 50;

    public static readonly ModSpec Mod = new(
        "ets2u_economy.scs", "ETS2 Utilities: Bigger earnings", "other",
        "Generated by ETS2 Utilities. Multiplies truck job pay and XP. Change it from the app, not by hand.");

    public static byte[] Build(byte[] stock, double income, double xp)
    {
        income = Math.Clamp(income, 1, MaxMultiplier);
        xp = Math.Clamp(xp, 1, MaxMultiplier);
        if (income == 1 && xp == 1) return stock;

        var doc = SiiDocument.Parse(stock);
        var unit = doc.FindUnit(Unit) ?? throw new FormatException($"No {Unit} unit in {GamePath}.");
        Multiply(doc, unit, IncomeKeys, income);
        Multiply(doc, unit, XpKeys, xp);
        return doc.ToBytes();
    }

    public static byte[] BuildMod(byte[] stock, double income, double xp) =>
        ScsModBuilder.Build(Mod, new Dictionary<string, byte[]> { [GamePath] = Build(stock, income, xp) });

    static void Multiply(SiiDocument doc, SiiUnit unit, string[] keys, double factor)
    {
        if (factor == 1) return;
        foreach (var key in keys)
        {
            var raw = doc.GetValue(unit, key);
            if (raw is null || !double.TryParse(raw, NumberStyles.Float, CultureInfo.InvariantCulture, out var v))
                throw new FormatException($"{key} missing or not a number in {GamePath}.");
            doc.SetValue(unit, key, (v * factor).ToString("0.####", CultureInfo.InvariantCulture));
        }
    }
}
