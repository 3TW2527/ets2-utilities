using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using Ets2u.Core.Mods;
using Ets2u.Core.Sii;

namespace Ets2u.Core.Features;

/// <summary>The colour of the destination display's LEDs.</summary>
public enum DisplayColor { Amber, Orange, Yellow, White, Green }

/// <summary>What the coach's front destination display shows.</summary>
public sealed class BusDisplaySettings
{
    public bool Enabled { get; set; }

    /// <summary>Route number shown before the text, e.g. "X42". Optional.</summary>
    public string Route { get; set; } = "";

    /// <summary>The text. {destination} is replaced by the game's own destination (only known on a job).</summary>
    public string Text { get; set; } = BusDisplay.DestinationToken;

    public DisplayColor Color { get; set; } = DisplayColor.Amber;

    /// <summary>1 = the game's letter size; smaller fits longer text on the display.</summary>
    public double Size { get; set; } = 1;
}

/// <summary>
/// Changes the text on the coaches' front destination display (the "standard destination display"
/// upgrade). How the game draws it, from dlc_bus.scs:
/// <list type="bullet">
/// <item>ui/dashboard/bus_panel_generic.sii is a 512x85 UI window with one text element (id 10) that the
/// game fills with the job's destination, laid out by the template <c>txt.dlc_bus.bus_panel</c>.</item>
/// <item>That template, in ui/template/dashboard_text.dlc_bus.sii, is one line of markup: font, size,
/// colour and <c>%0</c>, where the game's text goes.</item>
/// </list>
/// So this mod ships that template with the user's text in place of (or around) <c>%0</c>. Without
/// <c>%0</c> the text no longer depends on the job, so it shows with or without one, whenever the
/// ignition is on. The game reads UI files when it starts, so a change needs a restart.
/// </summary>
public static class BusDisplay
{
    public const string GamePath = "ui/template/dashboard_text.dlc_bus.sii";
    public const string TemplateName = "txt.dlc_bus.bus_panel";
    public const string DestinationToken = "{destination}";
    public const int MaxLength = 60;

    public static readonly ModSpec Mod = new(
        "ets2u_busdisplay", "ETS2 Utilities: Destination display", "ui",
        "Generated by ETS2 Utilities. Shows your own text on the coaches' front destination display.\n" +
        "Change it from the app, not by hand.");

    /// <summary>LED colours as the game writes them: AABBGGRR. Amber is the game's own.</summary>
    public static string ColorValue(DisplayColor color) => color switch
    {
        DisplayColor.Orange => "FF0070FF",
        DisplayColor.Yellow => "FF00E6FF",
        DisplayColor.White => "FFF0F0F0",
        DisplayColor.Green => "FF40FF60",
        _ => "FF03B0FA",
    };

    /// <summary>
    /// What goes between the template's &lt;nowrap&gt; tags. Markup characters are dropped (the display
    /// would read them as tags), and so are characters the SII string can't hold.
    /// </summary>
    public static string Content(string route, string text)
    {
        static string Clean(string s) =>
            new string(s.Where(c => c is not ('<' or '>' or '"' or '\\' or '%') && !char.IsControl(c)).ToArray());

        var body = string.Join("%0", text.Split(DestinationToken, StringSplitOptions.None).Select(Clean)).Trim();
        var r = Clean(route).Trim();
        var all = r.Length == 0 ? body : body.Length == 0 ? r : r + "  " + body;
        if (all.Replace("%0", "").Length > MaxLength)
            throw new FormatException($"The display holds one line: keep it to {MaxLength} characters.");
        return all;
    }

    public static bool ShowsGameDestination(BusDisplaySettings s) => s.Text.Contains(DestinationToken, StringComparison.Ordinal);

    /// <summary>The template file to ship: the stock one with the user's text, colour and size.</summary>
    public static byte[] Build(byte[] stock, BusDisplaySettings s)
    {
        if (!s.Enabled) return stock;
        var doc = SiiDocument.Parse(stock);
        var unit = doc.Units.FirstOrDefault(u => u.Name == TemplateName)
                   ?? throw new FormatException($"No {TemplateName} template in {GamePath}: the game changed.");
        var markup = doc.GetValue(unit, "text") ?? throw new FormatException($"The {TemplateName} template has no text.");

        var changed = Replace(markup, @"<nowrap>%0</nowrap>", "<nowrap>" + Content(s.Route, s.Text) + "</nowrap>", literal: true);
        changed = Replace(changed, @"(?<=<color value=)[0-9A-Fa-f]{8}", ColorValue(s.Color));
        var size = Math.Clamp(s.Size, 0.3, 1.5);
        changed = Regex.Replace(changed, @"(?<=\b[xy]scale=)[\d.]+", m =>
            (double.Parse(m.Value, CultureInfo.InvariantCulture) * size).ToString("0.##", CultureInfo.InvariantCulture));
        doc.SetValue(unit, "text", changed);
        return doc.ToBytes();
    }

    static string Replace(string input, string pattern, string replacement, bool literal = false)
    {
        var regex = new Regex(literal ? Regex.Escape(pattern) : pattern);
        if (!regex.IsMatch(input)) throw new FormatException($"The display template no longer has {pattern}: the game changed.");
        return regex.Replace(input, replacement.Replace("$", "$$"), 1);
    }

    public static byte[] BuildMod(byte[] stock, BusDisplaySettings s) =>
        ScsModBuilder.Build(Mod, new Dictionary<string, byte[]> { [GamePath] = Build(stock, s) });

    /// <summary>
    /// A list of display texts, one per line: "route | text" or just "text". Blank lines and lines
    /// starting with # are skipped. Reads lazily, so a list of millions doesn't need to fit in a list box.
    /// </summary>
    public static IEnumerable<(string Route, string Text)> ReadList(TextReader reader)
    {
        while (reader.ReadLine() is { } line)
        {
            var t = line.Trim();
            if (t.Length == 0 || t.StartsWith('#')) continue;
            var bar = t.IndexOf('|');
            yield return bar < 0 ? ("", t) : (t[..bar].Trim(), t[(bar + 1)..].Trim());
        }
    }

    public static string ListLine(string route, string text) => route.Length == 0 ? text : $"{route} | {text}";

    public static Encoding ListEncoding => new UTF8Encoding(false);
}
