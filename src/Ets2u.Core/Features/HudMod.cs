using Ets2u.Core.Extract;
using Ets2u.Core.Mods;
using Ets2u.Core.Sii;

namespace Ets2u.Core.Features;

/// <summary>
/// Moves the route advisor map by overriding ui/adviser.sii. Each HUD block there has a
/// "standard" layout (left-hand-drive trucks: map bottom-right) and a "uk" layout
/// (right-hand-drive trucks: map bottom-left). Trucks and coaches share this file.
/// The map block (.adv_hud_r) and the tachometer block (.adv_hud_l) always move together
/// so they never land in the same corner.
/// </summary>
public static class HudMod
{
    // Only the desktop layout: the VR one (adviser_oculus.sii) has a single centred block, nothing to move.
    public static readonly string[] GamePaths = ["ui/adviser.sii"];

    const string MapBlock = ".adv_hud_r";
    const string TachoBlock = ".adv_hud_l";

    public static readonly ModSpec Mod = new(
        "ets2u_ui.scs", "ETS2 Utilities: Route advisor position", "ui",
        "Generated by ETS2 Utilities. Moves the route advisor map. Change it from the app, not by hand.");

    /// <summary>Layout keys that come in standard/uk pairs.</summary>
    static IEnumerable<(string Standard, string Uk)> Pairs(SiiDocument doc, SiiUnit unit)
    {
        yield return ("window_keep_aspect_standard", "window_keep_aspect_uk");
        foreach (var key in unit.Keys.Where(k => k.StartsWith("standard_", StringComparison.Ordinal)))
        {
            var uk = "uk_" + key["standard_".Length..];
            if (doc.GetValue(unit, uk) is not null) yield return (key, uk);
        }
    }

    public static byte[] Build(byte[] stock, MapSide side)
    {
        var doc = SiiDocument.Parse(stock);
        foreach (var name in new[] { MapBlock, TachoBlock })
        {
            var unit = doc.Units.FirstOrDefault(u => u.Name == name)
                       ?? throw new FormatException($"No {name} block in the route advisor script.");
            foreach (var (standardKey, ukKey) in Pairs(doc, unit).ToList())
            {
                var standard = doc.GetValue(unit, standardKey)!;
                var uk = doc.GetValue(unit, ukKey)!;
                // Stock: the map's standard layout is right and its uk layout left; the tachometer's is the
                // reverse. So "map left" means both blocks use their uk layout, "map right" their standard one.
                var (newStandard, newUk) = side switch
                {
                    MapSide.Swap => (uk, standard),
                    MapSide.Left => (uk, uk),
                    MapSide.Right => (standard, standard),
                    _ => (standard, uk),
                };
                doc.SetValue(unit, standardKey, newStandard);
                doc.SetValue(unit, ukKey, newUk);
            }
        }
        return doc.ToBytes();
    }

    /// <summary>The mod: patched adviser scripts when enabled, stock ones when off.</summary>
    public static byte[] BuildMod(IGameFiles game, AppSettings settings)
    {
        var files = new Dictionary<string, byte[]>();
        foreach (var path in GamePaths)
        {
            if (game.TryRead(path) is not { } stock) continue;
            files[path] = settings.MapPositionEnabled ? Build(stock, settings.MapSide) : stock;
        }
        if (files.Count == 0) throw new FileNotFoundException("The route advisor script isn't in the game's archives.");
        return ScsModBuilder.Build(Mod, files);
    }

    public static string DescribeMapSupport(IGameFiles game) =>
        game.TryRead(GamePaths[0]) is null
            ? "The route advisor script wasn't found in the extracted game files."
            : "The game puts the map bottom-right in left-hand-drive trucks and coaches, and bottom-left in UK " +
              "right-hand-drive ones. The tachometer block moves to the other corner so they never overlap.";
}
