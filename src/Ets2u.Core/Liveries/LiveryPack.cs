using System.IO.Compression;
using System.Security.Cryptography;
using System.Text;
using Ets2u.Core.Extract;
using Ets2u.Core.Mods;
using Ets2u.Core.Paths;

namespace Ets2u.Core.Liveries;

public enum LiverySourceKind { Local, Workshop }

/// <summary>One mod whose liveries go into the pack.</summary>
public sealed class LiverySource
{
    public LiverySourceKind Kind { get; set; }

    /// <summary>A local mod's folder or .scs/.zip file. Unused for Workshop items.</summary>
    public string? Path { get; set; }

    public string? WorkshopId { get; set; }

    /// <summary>Shown in the app and in the pack's description.</summary>
    public string Name { get; set; } = "";

    public string? Author { get; set; }

    /// <summary>Unticked sources stay in the list but are left out of the pack.</summary>
    public bool Included { get; set; } = true;

    public string Key => Kind == LiverySourceKind.Workshop ? "workshop:" + WorkshopId : "local:" + System.IO.Path.GetFullPath(Path ?? "");

    public string Where => Kind == LiverySourceKind.Workshop ? $"Workshop {WorkshopId}" : Path ?? "";
}

public sealed class LiveryPackSettings
{
    public bool Enabled { get; set; }
    public List<LiverySource> Sources { get; set; } = new();

    /// <summary>The user confirmed the creators of the Workshop items allow repacking.</summary>
    public bool WorkshopPermissionConfirmed { get; set; }

    /// <summary>What the pack was last built from (see <see cref="LiveryPack.Fingerprint"/>); a change means it's rebuilt.</summary>
    public string? BuiltFingerprint { get; set; }
}

/// <summary>What one source adds to the pack.</summary>
public sealed record SourceReport(LiverySource Source, string? Package, int Files, int PaintJobs, IReadOnlyList<string> Overrides, string? Problem);

/// <summary>Everything the pack will hold, and anything worth knowing before building it.</summary>
public sealed record PackPlan(
    IReadOnlyList<SourceReport> Sources,
    IReadOnlyDictionary<string, LiverySource> Files,
    IReadOnlyList<string> Conflicts)
{
    public int PaintJobs => Sources.Sum(s => s.PaintJobs);
}

/// <summary>
/// Puts the liveries of many mods into one mod, so the Mod Manager shows one entry instead of one per
/// livery. Each source's files go in at the same paths; files at a mod's root (manifest, description,
/// pictures, versions.sii) are left out and a new manifest is written. When two sources hold the same
/// path with different contents, the one higher in the list wins and the clash is reported.
/// </summary>
public static class LiveryPack
{
    public static readonly ModSpec Mod = new(
        "ets2u_liveries", "ETS2 Utilities: Livery pack", "paint_job",
        "Generated by ETS2 Utilities from several livery mods. Change it from the app, not by hand.");

    /// <summary>A paint job definition: def/vehicle/&lt;kind&gt;/&lt;brand.model&gt;/paint_job/*.sii.</summary>
    public static bool IsPaintJob(string path)
    {
        if (!path.StartsWith("def/vehicle/", StringComparison.OrdinalIgnoreCase)
            || !path.EndsWith(".sii", StringComparison.OrdinalIgnoreCase)) return false;
        var at = path.IndexOf("/paint_job/", StringComparison.OrdinalIgnoreCase);
        // Directly in paint_job/: paint_job/accessory/... holds the parts that come with one, not more paint jobs.
        return at >= 0 && path.IndexOf('/', at + "/paint_job/".Length) < 0;
    }

    /// <summary>Root files belong to the source mod itself, not to the game.</summary>
    public static bool IsModMetadata(string path) => !path.Contains('/');

    /// <summary>The folder or archive to read for a source, or null (with the reason) if it's gone.</summary>
    public static (string? Package, string? Problem) Resolve(LiverySource source, GamePaths paths)
    {
        if (source.Kind == LiverySourceKind.Local)
            return source.Path is { } p && (File.Exists(p) || Directory.Exists(p)) ? (p, null) : (null, "The file or folder is gone.");
        var dir = source.WorkshopId is null ? null : Workshop.FindItemDir(paths, source.WorkshopId);
        if (dir is null) return (null, "Not downloaded: subscribe to it on the Workshop and let Steam download it.");
        return Workshop.PickPackage(dir, paths.GameVersion) is { } package
            ? (package, null)
            : (null, "No version of this item fits the installed game.");
    }

    /// <summary>
    /// What the pack would hold. <paramref name="game"/>, when given, is used to spot files that replace the
    /// game's own (liveries normally only add files).
    /// </summary>
    public static PackPlan Plan(IEnumerable<LiverySource> sources, GamePaths paths, IGameFiles? game = null)
    {
        var reports = new List<SourceReport>();
        var files = new Dictionary<string, LiverySource>(StringComparer.OrdinalIgnoreCase);
        var hashes = new Dictionary<string, byte[]>(StringComparer.OrdinalIgnoreCase);
        var conflicts = new List<string>();

        foreach (var source in sources.Where(s => s.Included))
        {
            var (package, problem) = Resolve(source, paths);
            if (package is null)
            {
                reports.Add(new SourceReport(source, null, 0, 0, [], problem));
                continue;
            }
            try
            {
                using var content = ModContent.Load(package);
                var mine = content.Files.Where(f => !IsModMetadata(f)).ToList();
                var overrides = game is null ? new List<string>()
                    : mine.Where(f => f.StartsWith("def/", StringComparison.OrdinalIgnoreCase) && game.TryRead(f) is not null).ToList();
                foreach (var file in mine)
                {
                    if (files.TryGetValue(file, out var first))
                    {
                        // Same bytes is no clash (e.g. a shared icon); hash lazily, only when paths collide.
                        hashes.TryAdd(file, HashOf(first, file, paths));
                        if (!HashOf(content, file).AsSpan().SequenceEqual(hashes[file]))
                            conflicts.Add($"{file}: {first.Name} and {source.Name} differ; {first.Name} is used.");
                        continue;
                    }
                    files[file] = source;
                }
                reports.Add(new SourceReport(source, package, mine.Count, mine.Count(IsPaintJob), overrides, null));
            }
            catch (Exception ex) when (ex is IOException or InvalidDataException or UnauthorizedAccessException)
            {
                reports.Add(new SourceReport(source, package, 0, 0, [], ex.Message));
            }
        }
        return new PackPlan(reports, files, conflicts);
    }

    static byte[] HashOf(ModContent content, string file)
    {
        using var s = content.Open(file);
        return SHA256.HashData(s);
    }

    static byte[] HashOf(LiverySource source, string file, GamePaths paths)
    {
        using var content = ModContent.Load(Resolve(source, paths).Package!);
        return HashOf(content, file);
    }

    /// <summary>The pack's description in Mod Manager: what's in it and where each livery came from.</summary>
    public static string Description(PackPlan plan)
    {
        var sb = new StringBuilder("Liveries packed by ETS2 Utilities. All credit goes to their creators:\n");
        foreach (var r in plan.Sources.Where(r => r.Problem is null))
        {
            sb.Append("- ").Append(r.Source.Name);
            if (!string.IsNullOrEmpty(r.Source.Author)) sb.Append(" by ").Append(r.Source.Author);
            if (r.Source.Kind == LiverySourceKind.Workshop) sb.Append(" (Workshop ").Append(r.Source.WorkshopId).Append(')');
            sb.Append('\n');
        }
        return sb.Append("\nChange it from the app, not by hand.").ToString();
    }

    /// <summary>
    /// Writes the pack to <paramref name="output"/>. It's streamed file by file, since liveries are big
    /// textures. Textures are stored as they are: DDS is already compressed, and the game reads stored
    /// entries fastest.
    /// </summary>
    public static void Write(Stream output, ModSpec spec, PackPlan plan, GamePaths paths, Action<int, int>? progress = null)
    {
        spec = spec with { Description = Description(plan) };
        using var zip = new ZipArchive(output, ZipArchiveMode.Create, leaveOpen: true);
        Add(zip, "manifest.sii", Encoding.UTF8.GetBytes(ScsModBuilder.Manifest(spec)));
        Add(zip, "description.txt", Encoding.UTF8.GetBytes(spec.Description));
        if (ScsModBuilder.Icon(spec) is { } icon) Add(zip, ScsModBuilder.IconFile, icon);

        var done = 0;
        foreach (var group in plan.Files.GroupBy(f => f.Value.Key))
        {
            var source = group.First().Value;
            using var content = ModContent.Load(Resolve(source, paths).Package
                                                ?? throw new FileNotFoundException($"{source.Name} disappeared while the pack was being built."));
            foreach (var path in group.Select(f => f.Key).OrderBy(p => p, StringComparer.Ordinal))
            {
                var entry = zip.CreateEntry(path, path.EndsWith(".dds", StringComparison.OrdinalIgnoreCase)
                    ? CompressionLevel.NoCompression : CompressionLevel.Fastest);
                entry.LastWriteTime = new DateTimeOffset(2026, 1, 1, 0, 0, 0, TimeSpan.Zero);
                using (var to = entry.Open())
                using (var from = content.Open(path))
                    from.CopyTo(to);
                progress?.Invoke(++done, plan.Files.Count);
            }
        }
    }

    static void Add(ZipArchive zip, string path, byte[] bytes)
    {
        var entry = zip.CreateEntry(path, CompressionLevel.Optimal);
        entry.LastWriteTime = new DateTimeOffset(2026, 1, 1, 0, 0, 0, TimeSpan.Zero);
        using var s = entry.Open();
        s.Write(bytes);
    }

    /// <summary>
    /// Changes whenever a source changes: a Workshop item updated by Steam, a local mod replaced, a source
    /// added, removed or (un)ticked. Built from file sizes and times, so it's quick even for big packs.
    /// </summary>
    public static string Fingerprint(IEnumerable<LiverySource> sources, GamePaths paths)
    {
        var sb = new StringBuilder();
        foreach (var source in sources.Where(s => s.Included))
        {
            sb.Append(source.Key).Append('\n');
            var (package, problem) = Resolve(source, paths);
            if (package is null)
            {
                sb.Append("missing\n");
                continue;
            }
            sb.Append(package).Append('\n');
            if (File.Exists(package))
            {
                var info = new FileInfo(package);
                sb.Append(info.Length).Append(' ').Append(info.LastWriteTimeUtc.Ticks).Append('\n');
            }
            else
            {
                foreach (var f in Directory.EnumerateFiles(package, "*", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
                {
                    var info = new FileInfo(f);
                    sb.Append(System.IO.Path.GetRelativePath(package, f)).Append(' ').Append(info.Length).Append(' ')
                        .Append(info.LastWriteTimeUtc.Ticks).Append('\n');
                }
            }
        }
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(sb.ToString())))[..16];
    }

    /// <summary>Sources the pack can't be built from right now, with the reason.</summary>
    public static IReadOnlyList<(LiverySource Source, string Problem)> Missing(IEnumerable<LiverySource> sources, GamePaths paths) =>
        sources.Where(s => s.Included)
            .Select(s => (s, Resolve(s, paths).Problem))
            .Where(x => x.Problem is not null)
            .Select(x => (x.s, x.Problem!))
            .ToList();
}
